export function buildPlotPointOutputFormatInstruction({
  count,
  hasChain,
}: {
  count: number;
  hasChain: boolean;
}) {
  const stageText = hasChain
    ? '同一批候选都必须处在“已选剧情链之后的同一个下一步进度”，例如都可以作为第二章/下一章的不同方案。'
    : '同一批候选都必须处在“小说开头的同一个进度”，例如都可以作为第一章开头的不同方案。';
  const forbiddenProgressText = hasChain
    ? '不要把 1 写成第二章、2 写成第三章、3 写成第四章；它们不是连续章节，而是同一下一步的多个备选。'
    : '不要把 1 写成第一章、2 写成第二章、3 写成第三章；它们不是连续章节，而是第一章开头的多个备选。';
  const openingStageRules = hasChain
    ? []
    : [
        '空剧情链时，每条候选都必须从读者第一次进入故事的开场场景写起：主角此刻在哪里、面对什么压力/羞辱/危机/异变、第一步做什么。',
        '空剧情链时，禁止默认前面已经发生过关键事件。不要写“系统已经激活后”“他迅速兑换/浏览商城”“爆炸已经造成结果后”“三天后/72小时内开始规划”等后续推进。',
        '空剧情链时，每条候选都要能独立放在第一章第一幕，不需要读者先读过另一条候选才能理解。',
      ];
  const bodyKind = hasChain ? '衔接剧情正文' : '开头剧情正文';
  const reviewKind = hasChain ? '它如何承接已选剧情链、为什么适合作为下一步' : '它为什么适合作为开头、冲突和期待感在哪里';
  return [
    `必须输出 ${count} 个候选剧情点，编号必须从 1-${count} 连续排列，不要少于 ${count} 个。`,
    stageText,
    forbiddenProgressText,
    ...openingStageRules,
    '每个编号都是一个可供用户挑选的独立备选方案，彼此可以风格不同、冲突不同、切入点不同，但都服务于同一进度。',
    `每个剧情点只按以下格式输出：序号. 直接写一段${bodyKind}`,
    `AI评价：一句话说明${reviewKind}。`,
    '不要输出“标题：”，不要在正文开头写概念标题或场景小标题。',
    '每一条第一句都必须出现本书主角名字，不能用“他”“她”“主角”“少年”“发现自己”这类无姓名开头。',
    '第一句必须直接写人物、事件、冲突或行动。',
    '不要输出原型、原剧情点、变量替换过程、替换说明或改写说明。',
  ].join('\n');
}
