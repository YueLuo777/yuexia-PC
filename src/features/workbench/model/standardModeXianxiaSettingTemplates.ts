type EntryFieldSelection = Record<string, readonly string[]>;

function selectTemplateFields(structure: TemplateStructure, selection: EntryFieldSelection): TemplateStructure {
  return structure
    .map((domain) => ({
      ...domain,
      groups: domain.groups
        .map((group) => ({
          ...group,
          entries: group.entries
            .filter((entry) => selection[entry.title])
            .map((entry) => {
              const allowedFields = new Set(selection[entry.title]);
              return {
                ...entry,
                sections: entry.sections
                  .map((section) => ({
                    ...section,
                    fields: section.fields.filter((field) => allowedFields.has(field.title)),
                  }))
                  .filter((section) => section.fields.length > 0),
              };
            }),
        }))
        .filter((group) => group.entries.length > 0),
    }))
    .filter((domain) => domain.groups.length > 0);
}

function extendFields(base: readonly string[], additions: readonly string[]) {
  return [...new Set([...base, ...additions])];
}

