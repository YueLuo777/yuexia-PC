export type AiReadyField = {
  label: string;
  value: string;
  compact?: boolean;
  colSpan?: 2 | 3 | 6;
};

export type AiReadySection = {
  title: string;
  columns: 2 | 6;
  fields: AiReadyField[];
};

export type AiReadyProfile = {
  kind: 'work' | 'role';
  title: string;
  group: string;
  identity?: string;
  tag?: '男主' | '女主' | '配角' | '反派';
  sections: AiReadySection[];
  aiPrompt: string;
};

export type AiReadyEntry = {
  id: AiReadyPreviewId;
  title: string;
  domain: 'work' | 'character';
  group: string;
  tag?: AiReadyProfile['tag'];
};

const field = (label: string, value: string, options: Omit<AiReadyField, 'label' | 'value'> = {}): AiReadyField => ({
  label,
  value,
  ...options,
});

const buildBaseSection = (values: readonly [string, string, string, string, string]): AiReadySection => ({
  title: '基础档案',
  columns: 6,
  fields: [
    field('外貌', values[0], { compact: true, colSpan: 2 }),
    field('性格', values[1], { compact: true, colSpan: 2 }),
    field('称号与别名', values[2], { compact: true, colSpan: 2 }),
    field('人物背景', values[3], { colSpan: 3 }),
    field('当前目标', values[4], { colSpan: 3 }),
  ],
});

const buildConstraintSection = (values: readonly [string, string, string, string]): AiReadySection => ({
  title: '动机与行为规则',
  columns: 2,
  fields: [
    field('核心动机', values[0]),
    field('行为原则与底线', values[1]),
    field('语言习惯与标志动作', values[2]),
    field('角色已知信息与错误认知', values[3]),
  ],
});

const buildStrengthSection = (values: readonly [string, string, string, string, string]): AiReadySection => ({
  title: '实力与手段',
  columns: 2,
  fields: [
    field('境界修为', values[0]),
    field('功法体系', values[1]),
    field('战斗技能', values[2]),
    field('其他技能', values[3]),
    field('战力范围与弱点', values[4], { colSpan: 2 }),
  ],
});

const buildStorySection = (values: readonly [string, string, string, string]): AiReadySection => ({
  title: '剧情职能',
  columns: 2,
  fields: [
    field('剧情作用', values[0]),
    field('利益立场', values[1]),
    field('关键剧情节点', values[2]),
    field('成长变化', values[3]),
  ],
});

const buildCurrentSection = (values: readonly [string, string, string, string]): AiReadySection => ({
  title: '当前状态',
  columns: 2,
  fields: [
    field('当前处境', values[0]),
    field('当前地点', values[1]),
    field('身心状态', values[2]),
    field('当前资源', values[3]),
  ],
});

const buildRelationshipSection = (values: readonly [string, string]): AiReadySection => ({
  title: '关系',
  columns: 2,
  fields: [field('人物关系', values[0]), field('隶属势力', values[1])],
});

